def fetch_data(symbol: str, ltf: str = "1h", htf: str = "1d",
               period: str = "6mo") -> tuple[pd.DataFrame, pd.DataFrame]:
    """Download lower- and higher-timeframe OHLCV data from Yahoo Finance."""
    print(f"Downloading {symbol} {ltf} and {htf} data...")
    df_ltf = yf.download(symbol, period=period, interval=ltf, progress=False,
                         auto_adjust=True)
    df_htf = yf.download(symbol, period=period, interval=htf, progress=False,
                         auto_adjust=True)
    # yfinance may return MultiIndex columns; flatten
    if isinstance(df_ltf.columns, pd.MultiIndex):
        df_ltf.columns = df_ltf.columns.get_level_values(0)
    if isinstance(df_htf.columns, pd.MultiIndex):
        df_htf.columns = df_htf.columns.get_level_values(0)
    df_ltf.columns = [c.lower() for c in df_ltf.columns]
    df_htf.columns = [c.lower() for c in df_htf.columns]
    df_ltf = df_ltf.dropna(subset=["open", "high", "low", "close"])
    df_htf = df_htf.dropna(subset=["open", "high", "low", "close"])
    print(f"  LTF bars: {len(df_ltf)}, HTF bars: {len(df_htf)}")
    return df_ltf, df_htf


def summarize(trades: list[Trade], initial_capital: float = 10000.0,
              risk_per_trade_pct: float = 1.0) -> dict:
    """Compute honest performance statistics from the trade list.

    PnL is measured in R (risk units) with TP1 scaling: half the position banks
    1R, the rest runs to TP2 or the stop (or breakeven once TP1 is banked)."""
    closed = [t for t in trades if t.outcome in ("win", "loss", "be")]
    n = len(closed)
    if n == 0:
        return {"trades": 0}

    wins = [t for t in closed if t.outcome == "win"]
    losses = [t for t in closed if t.outcome == "loss"]
    be = [t for t in closed if t.outcome == "be"]
    rs = [getattr(t, "r_multiple", 0.0) for t in closed]
    total_r = sum(rs)

    # Equity curve: fixed-fractional risk, each trade's R applied to capital.
    capital = initial_capital
    equity = [capital]
    for t in closed:
        capital *= (1 + (risk_per_trade_pct / 100.0) * getattr(t, "r_multiple", 0.0))
        equity.append(capital)
    equity_arr = np.array(equity)
    peak = np.maximum.accumulate(equity_arr)
    drawdown = (equity_arr - peak) / peak * 100

    return {
        "trades": n,
        "wins": len(wins),
        "losses": len(losses),
        "be": len(be),
        "win_rate": len(wins) / n * 100,
        "expectancy_r": total_r / n,
        "total_r": total_r,
        "avg_win_pct": np.mean([t.pnl_pct for t in wins]) if wins else 0.0,
        "avg_loss_pct": np.mean([t.pnl_pct for t in losses]) if losses else 0.0,
        "final_capital": capital,
        "max_drawdown_pct": drawdown.min(),
        "equity": equity_arr,
    }


def print_report(stats: dict, trades: list[Trade], symbol: str, rr: float):
    print("\n" + "=" * 60)
    print(f" OTE + SMC BACKTEST REPORT — {symbol}  (target RR={rr})")
    print("=" * 60)
    if stats.get("trades", 0) == 0:
        print("  No closed trades generated by the strategy.")
        print("  The strategy may be too selective for this data/symbol.")
        return
    print(f"  Total closed trades : {stats['trades']}")
    print(f"  Wins / Losses / BE  : {stats['wins']} / {stats['losses']} / {stats['be']}")
    print(f"  Win rate            : {stats['win_rate']:.1f}%")
    print(f"  Expectancy (R)      : {stats['expectancy_r']:+.3f} R per trade")
    print(f"  Total (R)           : {stats['total_r']:+.1f} R")
    print(f"  Avg win (pct)       : {stats['avg_win_pct']:+.2f}%")
    print(f"  Avg loss (pct)      : {stats['avg_loss_pct']:+.2f}%")
    print(f"  Final capital (sim) : ${stats['final_capital']:,.2f}  (1% risk/trade)")
    print(f"  Max drawdown        : {stats['max_drawdown_pct']:.2f}%")
    print("-" * 60)
    print("  NOTE: simulated. Does not include spread, slippage, commissions,")
    print("  margin calls, or real market impact. Real results will differ.")
    print("=" * 60)


def print_trades(trades: list[Trade], df_ltf: pd.DataFrame, limit: int = 20):
    closed = [t for t in trades if t.outcome in ("win", "loss", "be")]
    if not closed:
        return
    print(f"\n  Last {min(limit, len(closed))} closed trades:")
    print(f"  {'#':>3} {'Dir':>5} {'Entry':>10} {'Exit':>10} {'PnL%':>8} {'Outcome':>8}  Confluence")
    for i, t in enumerate(closed[-limit:], 1):
        conf = ",".join(t.confluence)
        print(f"  {i:>3} {t.direction:>5} {t.entry_price:>10.5f} "
              f"{t.exit_price:>10.5f} {t.pnl_pct:>+7.2f}% {t.outcome:>8}  {conf}")


def main():
    parser = argparse.ArgumentParser(description="OTE+SMC strategy backtest")
    parser.add_argument("--symbol", default="EURUSD=X", help="Yahoo ticker")
    parser.add_argument("--ltf", default="1h", help="lower timeframe (e.g. 1h, 30m)")
    parser.add_argument("--htf", default="1d", help="higher timeframe (e.g. 1d, 4h)")
    parser.add_argument("--period", default="6mo", help="lookback period")
    parser.add_argument("--rr", type=float, default=2.0, help="reward-to-risk")
    parser.add_argument("--min-confluence", type=int, default=2,
                        help="min PD arrays inside OTE")
    parser.add_argument("--strict", action="store_true",
                        help="require a candlestick pattern AND an ICT signal")
    args = parser.parse_args()

    df_ltf, df_htf = fetch_data(args.symbol, args.ltf, args.htf, args.period)
    if len(df_ltf) < 60:
        print("Not enough LTF data to run the strategy.", file=sys.stderr)
        sys.exit(1)

    trades = run_strategy(
        df_ltf, df_htf,
        rr_ratio=args.rr,
        atr_mult_stop=1.5,
        min_confluence=args.min_confluence,
        strict=args.strict,
    )
    stats = summarize(trades)
    print_report(stats, trades, args.symbol, args.rr)
    print_trades(trades, df_ltf)


if __name__ == "__main__":
    main()
